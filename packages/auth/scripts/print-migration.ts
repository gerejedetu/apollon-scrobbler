/**
 * Prints the SQL that creates Better Auth's tables for the current plugin set, for a D1 migration file.
 * Usage: vp run @scrobbler/auth#migration > packages/db-d1/migrations/0001_auth.sql
 * (then review the diff: regenerate whenever Better Auth or its plugins change).
 */
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { createAuth } from "../src/index.ts";

const auth = createAuth({
  database: new DatabaseSync(":memory:"),
  secret: "x".repeat(32),
  baseURL: "http://localhost",
  onAccountCreated: async () => {},
});

const { compileMigrations } = await getMigrations(auth.options);
const sql = await compileMigrations();
process.stdout.write(`-- Better Auth tables (generated by packages/auth/scripts/print-migration.ts; do not edit by hand).\n\n${sql.trim()}\n`);
